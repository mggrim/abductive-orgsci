/** Build the whole directory as a pure path→content map. */
export function buildWikiFiles(input: {
  readonly project: Project;
  readonly graph: OntologyGraph;
  readonly events: readonly LedgerEvent[];
}): readonly WikiFile[] {
  const { project, graph, events } = input;
  const pages = livePages(graph);
  const filenames = pageFilenames(pages);
  const doubts = originDoubts(events, project.id);

  return [
    { path: "README.md", content: README },
    { path: "index.md", content: indexFile(project, graph, filenames, events, doubts) },
    { path: "log.md", content: logFile(events, graph) },
    ...pages.map((page) => ({
      path: `pages/${filenames.get(page.id) ?? `${page.id}.md`}`,
      content: pageBody(page, graph, filenames, doubts),
    })),
  ];
}

/** Minimal structural typing of the File System Access API we actually use. */
interface DirectoryHandleLike {
  getDirectoryHandle(name: string, options?: { create?: boolean }): Promise<DirectoryHandleLike>;
  getFileHandle(name: string, options?: { create?: boolean }): Promise<{
    createWritable(): Promise<{ write(data: string): Promise<void>; close(): Promise<void> }>;
  }>;
}

export class WikiExportUnsupportedError extends Error {
  constructor() {
    super(
      "This browser cannot write a folder (it lacks the File System Access API). Use the JSON exports instead, " +
        "or open Abductive in a Chromium-based browser.",
    );
    this.name = "WikiExportUnsupportedError";
  }
}

/**
 * Write the files into a directory the user picks. The only impure part of
 * this module, and the only part that cannot run under `bun test`.
 */
export async function writeWikiDirectory(
  files: readonly WikiFile[],
  pickDirectory?: () => Promise<DirectoryHandleLike>,
): Promise<number> {
  const picker =
    pickDirectory ??
    (() => {
      const showDirectoryPicker = (globalThis as { showDirectoryPicker?: () => Promise<DirectoryHandleLike> })
        .showDirectoryPicker;
      if (showDirectoryPicker === undefined) throw new WikiExportUnsupportedError();
      return showDirectoryPicker();
    });

  const root = await picker();
  let written = 0;
  for (const file of files) {
    const segments = file.path.split("/");
    const name = segments.pop();
    if (name === undefined) continue;
    let dir = root;
    for (const segment of segments) {
      dir = await dir.getDirectoryHandle(segment, { create: true });
    }
    const handle = await dir.getFileHandle(name, { create: true });
    const writable = await handle.createWritable();
    await writable.write(file.content);
    await writable.close();
    written += 1;
  }
  return written;
}
