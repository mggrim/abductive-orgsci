export interface WikiFile {
  /** Path relative to the chosen directory, e.g. "pages/directors-decline.md". */
  readonly path: string;
  readonly content: string;
}

/*
 * Origin reaches this file in one register and through one call, `originWritten`.
 *
 * It was a private table here, a fourth set of words for the same three values
 * alongside the app's "yours", PagePanel's "your prior" and the graph key's
 * sentence. Round eight pointed the table's values at the module and left the
 * table standing, which meant a local name still sat between this file and the
 * definition and could be re-pointed at anything. Attribution in an exported
 * wiki is the one claim a reader outside the study can check, so the call is
 * direct: the words are unchanged, the indirection is gone.
 */

/** Stable, human-legible filenames. Collisions get the page id appended. */
export function pageFilenames(pages: readonly OntologyPage[]): Map<string, string> {
  const used = new Map<string, number>();
  const out = new Map<string, string>();
  for (const page of pages) {
    const base = slugify(page.title) || page.id;
    const seen = used.get(base) ?? 0;
    used.set(base, seen + 1);
    out.set(page.id, seen === 0 ? `${base}.md` : `${base}-${page.id.slice(0, 6)}.md`);
  }
  return out;
}

function frontmatter(page: OntologyPage): string {
  return [
    "---",
    `id: ${page.id}`,
    `type: ${page.type}`,
    `title: ${JSON.stringify(page.title)}`,
    `status: ${page.status}`,
    `origin: ${page.origin}`,
    `version: ${page.version}`,
    `supporting_chunks: [${page.supportingChunks.join(", ")}]`,
    `superseded_by: ${page.supersededBy ?? "null"}`,
    "---",
  ].join("\n");
}

function pageBody(
  page: OntologyPage,
  graph: OntologyGraph,
  filenames: ReadonlyMap<string, string>,
  doubts: ReadonlyMap<string, OriginDoubt>,
): string {
  const link = (id: string) => {
    const target = graph.pages.get(id);
    if (target === undefined) return id;
    return `[[${filenames.get(id)?.replace(/\.md$/, "") ?? id}|${target.title}]]`;
  };

  const parts = [frontmatter(page), "", `# ${page.title}`, ""];
  parts.push(page.body.trim() === "" ? "_No body written yet._" : page.body.trim(), "");

  const out = edgesFrom(graph, page.id);
  const incoming = edgesInto(graph, page.id);
  if (out.length > 0 || incoming.length > 0) {
    parts.push("## Links", "");
    for (const edge of out) {
      parts.push(`- **${relationReads(edge.role)}** → ${link(edge.to)}`);
    }
    for (const edge of incoming) {
      parts.push(`- ${link(edge.from)} **${relationReads(edge.role)}** this`);
    }
    parts.push("");
  }

  /* M89 (2026-10-14): "Open on this page" and "Dismissed on this page" listed
   * the checks' flags here until the checks left main. */

  if (page.history.length > 1) {
    parts.push("## Revisions", "");
    for (const v of page.history) {
      parts.push(`- v${v.version}, ${originWritten(v.origin)}: ${v.title}`);
    }
    parts.push("");
  }

  /* The attribution line carries the caveat, because this file IS the
   * attribution for one page.
   *
   * The wiki is generated by the same button row as memo.md and ontology.svg,
   * and it was the third file in that row asserting the claim flat while the
   * memo qualified it. A reader who takes the folder rather than the memo is
   * the reader most likely to quote the attribution line, because it is the
   * last sentence of the page they were reading. */
  const doubt = doubts.get(page.id);
  parts.push(
    "---",
    `_Attribution: ${
      doubt === undefined ? originWritten(page.origin) : originDoubtWritten(doubt)
    }. Generated from Abductive's History; edits to this file do not flow back._`,
  );
  return parts.join("\n");
}

function indexFile(
  project: Project,
  graph: OntologyGraph,
  filenames: ReadonlyMap<string, string>,
  events: readonly LedgerEvent[],
  doubts: ReadonlyMap<string, OriginDoubt>,
): string {
  const pages = livePages(graph);
  const doubted = doubtsOn(doubts, pages);
  const byType = new Map<PageType, OntologyPage[]>();
  for (const page of pages) {
    const list = byType.get(page.type) ?? [];
    list.push(page);
    byType.set(page.type, list);
  }

  const link = (page: OntologyPage) =>
    `- [${page.title}](pages/${filenames.get(page.id) ?? page.id}): _${
      doubts.has(page.id)
        ? `${originWritten(page.origin)}, ${ORIGIN_DOUBT_FLAG}`
        : originWritten(page.origin)
    }_`;

  const parts = [
    `# ${project.title}`,
    "",
    // The catalogue is the entry point a reader is told to start at, so it is
    // where this folder says which state of the design it is a copy of.
    `_${stampLine(events)}_`,
    "",
    ...puzzleExportLines(project.brief, decidedReading(events, project.id)),
    `${pages.length} live page${pages.length === 1 ? "" : "s"}, ${graph.puzzleRoots.length} puzzle root${graph.puzzleRoots.length === 1 ? "" : "s"}.`,
    "",
  ];

  // Before the catalogue, on the same argument the memo makes for putting it
  // before the attribution figure: a list of pages each labelled with who wrote
  // them should not be read first and qualified second.
  if (doubted.length > 0) parts.push(`_${originDoubtCaveat(doubted.length)}_`, "");

  if (graph.puzzleRoots.length > 0) {
    parts.push("## Puzzle roots", "");
    for (const id of graph.puzzleRoots) {
      const page = graph.pages.get(id);
      if (page !== undefined) parts.push(link(page));
    }
    parts.push("");
  }

  // Headings, and they were the slug: "## analytic-residue" in the catalogue a
  // cold reader is told to start at, in the same folder whose page files spell
  // the same value "analytic residue" in their own prose. Sorted on the label
  // rather than the slug now, so the order a reader sees is the order of the
  // words in front of them. The front matter at the top of each page file
  // keeps the slug on purpose: that is a field to grep, not a word addressed
  // to anyone.
  const heading = (type: PageType): string => {
    const label = pageTypeLabel(type);
    return `${label.slice(0, 1).toUpperCase()}${label.slice(1)}`;
  };
  for (const [type, list] of [...byType.entries()].sort((a, b) =>
    heading(a[0]).localeCompare(heading(b[0])),
  )) {
    if (type === "puzzle") continue;
    parts.push(`## ${heading(type)}`, "");
    for (const page of list) parts.push(link(page));
    parts.push("");
  }

  /* Passages, not documents (M29, E3), because this builder is not handed the
   * corpus and the fix needs it: `contradicts` counts source documents, and
   * without the map every passage counts as its own source. So the memo can
   * read a claim as discharged that the app, the checks and the argument band
   * all read as owing. Closing it means threading `chunks` through this
   * builder's params and every call site, which is a change to make on purpose
   * rather than in passing. `buildAgentGraph` already takes the corpus and
   * passes it. */
  const obligations = checkAllObligations(graph);
  if (obligations.length > 0) {
    parts.push("## What your starting point claims owe", "");
    for (const o of obligations) {
      const puzzle = graph.pages.get(o.puzzleId)?.title ?? o.puzzleId;
      const theory = graph.pages.get(o.theoryId)?.title ?? o.theoryId;
      parts.push(
        `- **${puzzle}** ${o.relation} **${theory}**: ${o.discharged ? "discharged" : "**not yet discharged**"}. ${o.detail}`,
      );
    }
    parts.push("");
  }

  /* M89: "Contradictions held open", read off the checks' flags, went with them. */

  const residue = pages.filter((p) => p.type === "analytic-residue");
  parts.push("## What the account cannot absorb", "");
  if (residue.length === 0) {
    parts.push(
      "_No entries yet. On a project of any maturity that is itself worth questioning. That silence usually means that the account absorbed residue rather than that none arose._",
    );
  } else {
    for (const page of residue) parts.push(link(page));
  }
  parts.push("");

  /* M89: "Structural issues" and "Dismissed by the researcher", the checks'
     flags, went with them. */

  parts.push("---", "", "_Generated by Abductive. See `log.md` for the full mutation history._");
  return parts.join("\n");
}

function logFile(events: readonly LedgerEvent[], graph: OntologyGraph): string {
  const parts = [
    "# Mutation log",
    "",
    "Append-only. Every change to the ontology, oldest first, with who originated it.",
    "",
  ];
  let n = 0;
  for (const event of events) {
    if (event.type !== "ontology-mutation") continue;
    n += 1;
    const title = event.title ?? graph.pages.get(event.targetId)?.title ?? event.targetId;
    const edge =
      event.edge === undefined
        ? ""
        : ` (${relationReads(event.edge.role)}: ${graph.pages.get(event.edge.from)?.title ?? event.edge.from} → ${graph.pages.get(event.edge.to)?.title ?? event.edge.to})`;
    const chunks =
      event.supportingChunks === undefined || event.supportingChunks.length === 0
        ? "without a citation"
        : `cites ${event.supportingChunks.length}`;
    parts.push(
      `${n}. **${event.op}** ${title}${edge}: _${originWritten(event.origin)}_, ${chunks}`,
    );
  }
  if (n === 0) parts.push("_No ontology mutations recorded._");
  return parts.join("\n");
}

