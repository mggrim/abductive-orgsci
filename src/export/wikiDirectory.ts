/**
 * Wiki directory export (ISC-69).
 *
 * A folder of markdown files a person can open in any editor and read: typed
 * frontmatter, prose bodies, `[[wiki-links]]` between pages, a generated
 * `index.md` catalogue and an append-only `log.md`. The shape follows
 * Karpathy's LLM wiki: pages rather than nodes, links rather than a schema,
 * with one deliberate departure.
 *
 * Karpathy's wiki lints toward consistency: contradictions get resolved,
 * structure gets tidied. Ours must not. An abductive ontology holds rival
 * accounts open on purpose, so `index.md` reports contradictions and residue
 * as *content* under their own headings rather than as a to-do list, and the
 * README says so to whoever opens the folder without context.
 *
 * File generation is pure. `buildWikiFiles` returns a path→content map, and
 * `writeWikiDirectory` is the only part that touches the File System Access
 * API. That split is what makes the whole export testable in bun.
 */

