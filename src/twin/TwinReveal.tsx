/**
 * Gated modal-twin reveal (ISC-31, ISC-42).
 *
 * The twin content is NEVER rendered until the user reveals it:
 *   - at the anomaly stage, a direct reveal button (via 'stage-gate');
 *   - at any earlier stage, a warned two-step inline confirm (via 'on-demand')
 *     — an inline panel, never a browser dialog and never a blocking modal.
 * Every reveal appends a `reveal` ledger event before content is shown.
 * The revealed/confirming flags are ephemeral UI state (allowed, ISC-29);
 * the twin itself lives in the twins store and the reveal in the ledger.
 */

import { useState } from "react";
import type { Project } from "../state/projects.ts";
import { useLedger } from "../state/ledgerContext.tsx";
import { canRevealDirectly, makeRevealEvent, type ModalTwin } from "./twin.ts";

export function TwinReveal(props: {
  project: Project;
  twin: ModalTwin | null;
}) {
  const { project, twin } = props;
  const { append } = useLedger();
  const [revealed, setRevealed] = useState(false);
  const [confirming, setConfirming] = useState(false);
  const [busy, setBusy] = useState(false);

  const direct = canRevealDirectly(project.stage);

  async function reveal(via: "stage-gate" | "on-demand") {
    if (busy || revealed) return;
    setBusy(true);
    try {
      // The reveal event lands in the ledger BEFORE any content renders.
      await append(makeRevealEvent(project.id, via));
      setRevealed(true);
      setConfirming(false);
    } finally {
      setBusy(false);
    }
  }

  if (twin === null) {
    return (
      <section className="card">
        <h2>Modal baseline (twin)</h2>
        <p className="muted">
          Abductive generates a modal baseline when you lock the design brief, and keeps the
          baseline hidden until you choose to reveal it.
        </p>
      </section>
    );
  }

  return (
    <section className="card">
      <h2>Modal baseline (twin)</h2>

      {!revealed && (
        <>
          <p className="muted">
            This baseline is a deliberately conventional version of the same design, built
            from your brief alone, with your ontology left out. Comparing against it shows where
            your design diverges from the modal study. Reading it too early is the risk: it
            can anchor you to exactly the conventions it describes.
          </p>

          {direct && (
            <div className="btnrow">
              <button
                className="primary"
                disabled={busy}
                onClick={() => void reveal("stage-gate")}
              >
                Reveal modal baseline
              </button>
              <span className="muted" style={{ alignSelf: "center" }}>
                Available now because this project is in the anomaly-hunt stage.
                Abductive logs the reveal in History.
              </span>
            </div>
          )}

          {!direct && !confirming && (
            <div className="btnrow">
              <button className="danger" disabled={busy} onClick={() => setConfirming(true)}>
                Reveal modal baseline (warning: seeing this may anchor you)
              </button>
            </div>
          )}

          {!direct && confirming && (
            <div className="card twinwarn">
              <p>
                <strong>Early reveal warning.</strong> This project is still in the{" "}
                {project.stage} stage. Reading the modal baseline now may anchor your
                framing, site, and expectations to the conventional design before your
                own has taken shape. The reveal, including that it happened early,
                will be appended to the ledger.
              </p>
              <div className="btnrow">
                <button
                  className="danger"
                  disabled={busy}
                  onClick={() => void reveal("on-demand")}
                >
                  I understand, reveal it
                </button>
                <button disabled={busy} onClick={() => setConfirming(false)}>
                  Keep it hidden
                </button>
              </div>
            </div>
          )}
        </>
      )}

      {revealed && (
        <div>
          <p className="muted">
            Generated by {twin.model} ({twin.modelVersion}) at brief lock. This is the
            MODAL design: the median study this brief would conventionally produce.
            Your design earns its divergence wherever it departs from this with reasons.
          </p>
          <h3>Modal research-question framing</h3>
          <p style={{ whiteSpace: "pre-wrap" }}>{twin.researchQuestionFraming}</p>
          <h3>Modal site / sample logic</h3>
          <p style={{ whiteSpace: "pre-wrap" }}>{twin.siteSampleLogic}</p>
          <h3>Modal expected findings</h3>
          <p style={{ whiteSpace: "pre-wrap" }}>{twin.expectedFindings}</p>
        </div>
      )}
    </section>
  );
}
