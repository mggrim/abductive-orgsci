/**
 * M68, ISC-637 and ISC-638: the third walkthrough screen is "The outputs of a
 * project" (owner, 2026-10-02).
 *
 * The owner, with a screenshot of the third page: "The title for this page
 * should be brought down into the subsection at the top. The label for that
 * title should be the outputs of a project. There should also be images that
 * correspond with those outputs. Use codex to create those images."
 *
 * So the screen's h1 sits inside the white panel as the heading of the four
 * outputs, the eyebrow stays above the banner as on the other screens, and each
 * output carries a photograph above its label, sized and rounded like the three
 * governance vignettes below it. The four photos were generated by the lead
 * with Codex image generation (gpt-image-2) and are the only ones on this
 * surface with alt text: each depicts its output, where the six older photos are
 * decoration beside prose that already says what the section is.
 *
 * M89 (2026-10-14): the Checks output went with the tab, so three outputs
 * remain (the photo file for Checks stays in public/).
 */
import "fake-indexeddb/auto";
import { useDom } from "./dom.ts";
useDom();

import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import React, { act } from "react";
import { createRoot, type Root } from "react-dom/client";
import { renderToStaticMarkup } from "react-dom/server";
import { OUTPUTS_HEADING, Walkthrough, WALKTHROUGH_OUTPUTS, WALKTHROUGH_TITLES } from "../src/ui/Walkthrough.tsx";
import { IntroImage } from "../src/ui/Introduction.tsx";
import { STUDY_TAB_TITLE } from "../src/ui/routes.ts";
import { ONTOLOGY_TAB_LABEL } from "../src/concepts/vocabulary.ts";
import { LedgerProvider } from "../src/state/ledgerContext.tsx";
import { InMemoryLedgerStore } from "../src/ledger/ledger.ts";

const ROOT = join(import.meta.dir, "..");
const INTRO_CSS = readFileSync(join(ROOT, "src/ui/styles/intro.css"), "utf8");
let container: HTMLElement;
let root: Root;

beforeEach(() => {
  container = document.createElement("div");
  document.body.appendChild(container);
  root = createRoot(container);
});
afterEach(async () => {
  await act(async () => root.unmount());
  container.remove();
});

async function mountAt(screen: number): Promise<void> {
  await act(async () => {
    root.render(
      React.createElement(LedgerProvider, {
        store: new InMemoryLedgerStore(),
        children: React.createElement(Walkthrough),
      }),
    );
  });
  for (let i = 0; i < screen; i += 1) {
    const next = container.querySelector<HTMLElement>('[data-testid="walk-next"]');
    if (next === null) throw new Error("no Next");
    await act(async () => {
      next.click();
    });
  }
}

const q = (id: string): HTMLElement | null => container.querySelector(`[data-testid="${id}"]`);

describe("ISC-637: the title is the panel's heading and reads The outputs of a project", () => {
  test("the third title is the process heading, and the owner's label heads the outputs (M83)", () => {
    expect(WALKTHROUGH_TITLES[2]).toBe("Working with Abductive");
    expect(OUTPUTS_HEADING).toBe("The outputs of a project");
  });

  test("on screen 3 the h1 is inside the white panel, above the three outputs", async () => {
    await mountAt(2);
    const titles = container.querySelectorAll('[data-testid="walk-title"]');
    expect(titles).toHaveLength(1);
    const title = titles[0] as HTMLElement;
    expect(title.tagName).toBe("H1");
    expect(title.textContent).toBe("Working with Abductive");
    const panel = q("walk-panel");
    expect(panel?.contains(title)).toBe(true);
    const places = q("walk-places") as HTMLElement;
    expect(title.compareDocumentPosition(places) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy();
    // The list is labelled by the heading it sits under: since M83 the outputs' subhead.
    const sub = q("walk-outputs-head") as HTMLElement;
    expect(sub.textContent).toBe("The outputs of a project");
    expect(places.getAttribute("aria-labelledby")).toBe(sub.id);
  });

  test("the eyebrow stays above the screen, and the screen carries the banner", async () => {
    await mountAt(2);
    const screen = q("walk-screen") as HTMLElement;
    const eyebrow = container.querySelector(".walk-eyebrow") as HTMLElement;
    expect(eyebrow.textContent).toBe("Abductive");
    expect(screen.contains(eyebrow)).toBe(false);
    expect(eyebrow.compareDocumentPosition(screen) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy();
    expect(q("walk-backdrop")?.getAttribute("data-src")).toBe("/intro/obstacles.jpg");
  });

  test("screens 2 and 4 keep their title above the screen", async () => {
    for (const at of [1, 3]) {
      await mountAt(at);
      const title = q("walk-title") as HTMLElement;
      expect({ at, inScreen: (q("walk-screen") as HTMLElement).contains(title) }).toEqual({ at, inScreen: false });
      await act(async () => root.unmount());
      root = createRoot(container);
    }
  });
});

describe("ISC-638: a photo above each output, with alt text", () => {
  test("three outputs, in order, with their sentences unchanged (M89: Checks went)", () => {
    expect(WALKTHROUGH_OUTPUTS.map((o) => o.name)).toEqual(["History", ONTOLOGY_TAB_LABEL, "Export"]);
    expect(WALKTHROUGH_OUTPUTS.map((o) => o.line)).toEqual([
      // M83, ISC-699: History's line is about change over time.
      "Abductive keeps every change in order, so you can follow the project back to its start.",
      STUDY_TAB_TITLE.ontology,
      STUDY_TAB_TITLE.exports,
    ]);
  });

  test("each output names its own file and a one-sentence alt text", () => {
    expect(WALKTHROUGH_OUTPUTS.map((o) => o.src)).toEqual([
      "/intro/output-history.jpg",
      "/intro/output-ontology.jpg",
      "/intro/output-export.jpg",
    ]);
    for (const o of WALKTHROUGH_OUTPUTS) {
      // One sentence: a capital, one full stop at the end, none before it.
      expect({ alt: o.alt, one: /^[A-Z][^.!?]*\.$/.test(o.alt) }).toEqual({ alt: o.alt, one: true });
    }
    const alts = WALKTHROUGH_OUTPUTS.map((o) => o.alt.toLowerCase());
    expect(alts[0]).toContain("logbook");
    expect(alts[0]).toContain("fountain pen");
    expect(alts[1]).toContain("paper slips");
    expect(alts[1]).toContain("string");
    expect(alts[2]).toContain("folded diagram");
    expect(alts[2]).toContain("envelope");
  });

  test("on screen 3 the three photos render above their labels with their alt text", () => {
    /* Rendered to markup rather than mounted: a test DOM fails every image load,
     * and the failure unmounts the image (the missing-file behaviour, held in
     * the next two tests), so a mounted screen has no img left to read. */
    container.innerHTML = renderToStaticMarkup(
      React.createElement(LedgerProvider, {
        store: new InMemoryLedgerStore(),
        children: React.createElement(Walkthrough, { start: 2 }),
      }),
    );
    const items = [...container.querySelectorAll('[data-testid="walk-places"] > li')];
    expect(items).toHaveLength(3);
    items.forEach((li, i) => {
      const want = WALKTHROUGH_OUTPUTS[i];
      const wrap = li.querySelector(`[data-testid="walk-output-image-${i + 1}"]`) as HTMLElement;
      expect(wrap).not.toBeNull();
      expect(wrap.getAttribute("data-src")).toBe(want?.src ?? "");
      // Content, not decoration: the wrapper does not hide it.
      expect(wrap.getAttribute("aria-hidden")).toBeNull();
      const img = wrap.querySelector("img");
      expect(img?.getAttribute("src")).toBe(want?.src ?? "");
      expect(img?.getAttribute("alt")).toBe(want?.alt ?? "");
      expect(img?.hasAttribute("aria-hidden")).toBe(false);
      // The photo comes before the label.
      const label = li.querySelector(".walk-list-title") as HTMLElement;
      expect(label.textContent).toBe(want?.name ?? "");
      expect(wrap.compareDocumentPosition(label) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy();
    });
  });

  test("an IntroImage with no alt is still decoration", () => {
    const html = renderToStaticMarkup(React.createElement(IntroImage, { src: "/intro/hero.jpg", className: "x", testId: "deco" }));
    expect(html).toContain('alt=""');
    expect(html).toContain('aria-hidden="true"');
  });

  test("an output photo that fails to load leaves the label and its sentence", async () => {
    // Mounted, every load fails in a test DOM: the photos go, the outputs stay.
    await mountAt(2);
    expect(container.querySelectorAll('[data-testid="walk-places"] img')).toHaveLength(0);
    expect(container.querySelectorAll('[data-testid="walk-places"] .walk-list-title')).toHaveLength(3);
    expect(container.querySelectorAll('[data-testid^="walk-output-image-"]')).toHaveLength(3);
  });

  test("the three files are in public/intro as square JPEGs the size of the vignettes", () => {
    const size = (file: string): { w: number; h: number } => {
      // Walk the JPEG markers to the first start-of-frame and read its size.
      const b = readFileSync(file);
      expect(b[0] === 0xff && b[1] === 0xd8).toBe(true);
      let i = 2;
      while (i < b.length) {
        const marker = b[i + 1] ?? 0;
        const len = ((b[i + 2] ?? 0) << 8) | (b[i + 3] ?? 0);
        if (marker >= 0xc0 && marker <= 0xc3) {
          return { h: ((b[i + 5] ?? 0) << 8) | (b[i + 6] ?? 0), w: ((b[i + 7] ?? 0) << 8) | (b[i + 8] ?? 0) };
        }
        i += 2 + len;
      }
      return { w: 0, h: 0 };
    };
    const vignette = size(join(ROOT, "public/intro/commit-1.jpg"));
    for (const o of WALKTHROUGH_OUTPUTS) {
      const file = join(ROOT, "public", o.src);
      expect({ file: o.src, exists: existsSync(file) }).toEqual({ file: o.src, exists: true });
      expect({ file: o.src, ...size(file) }).toEqual({ file: o.src, ...vignette });
    }
  });

  test("the photos take the vignettes' size and radius, three across and two at phone width", () => {
    // Same box as the governance vignettes: the shared width token and the
    // shared `.commitment-image` square and radius.
    expect(/\.walk-commit-image,\s*\.walk-output-image \{[^}]*width: 6rem/.test(INTRO_CSS)).toBe(true);
    const grid = /\.walk-outputs \{[^}]*\}/.exec(INTRO_CSS)?.[0] ?? "";
    expect(grid).toContain("grid-template-columns: repeat(3, minmax(0, 1fr))");
    const phone = /@media \(max-width: 700px\) \{[^@]*\.walk-outputs \{[^}]*\}/.exec(INTRO_CSS)?.[0] ?? "";
    expect(phone).toContain("grid-template-columns: repeat(2, minmax(0, 1fr))");
  });

  test("at phone width no list on the screen is wider than the panel", () => {
    // Measured at 390 on main before M68: the panel's body was 190px and the
    // governance triple's 16rem column minimum made both lists 256px, so the
    // panel's right edge and the title were cut off by the screen's clip. The
    // minimum is capped at the list's own width, which changes nothing wider.
    const list = /\.walk-list \{[^}]*\}/.exec(INTRO_CSS)?.[0] ?? "";
    expect(list).toContain("grid-template-columns: repeat(auto-fit, minmax(min(16rem, 100%), 1fr))");
    // And a photo is never wider than its column (87px at 390).
    expect(/\.walk-commit-image,\s*\.walk-output-image \{[^}]*max-width: 100%/.test(INTRO_CSS)).toBe(true);
    expect(/\.walk-outputs > li \{[^}]*grid-template-columns: minmax\(0, 1fr\)/.test(INTRO_CSS)).toBe(true);
  });
});
